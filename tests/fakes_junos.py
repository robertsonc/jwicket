@functools.lru_cache(maxsize=1)
def cryptography_works() -> bool:
    """Whether this Python can make a real certificate (transport.make_tls_pair): probed in a child
    process, because a broken cryptography install can abort the interpreter instead of raising
    ImportError. The 3.7 and 3.8 test runs have no cryptography; the install-autospec job has it."""
    probe = "import cryptography.x509, cryptography.hazmat.primitives.asymmetric.rsa"
    try:
        done = subprocess.run(  # noqa: S603 - this interpreter, fixed arguments, no shell
            [sys.executable, "-I", "-c", probe], capture_output=True, timeout=60, check=False
        )
    except (OSError, subprocess.TimeoutExpired):
        return False
    return done.returncode == 0


_FIXTURE_PAIRS = itertools.count(1)


def fixture_tls_pair(address: str) -> transport.TlsPair:
    """A placeholder PEM pair for runs without the cryptography library: the executor and this fake treat
    the pair as opaque bytes, and its fingerprint is the SHA-256 of its DER body, as for a real one. The
    key line is a planted marker, so a test can look for it in every output and record. Each call makes a
    different certificate (a counter in its body), as a real maker would, so two runs never share a pin."""
    der = f"fixture certificate {next(_FIXTURE_PAIRS)} for {plan.canonical_address(address)}".encode("ascii")
    cert = b"-----BEGIN CERTIFICATE-----\n" + base64.encodebytes(der) + b"-----END CERTIFICATE-----\n"
    key = b"-----BEGIN PRIVATE KEY-----\nRklYVFVSRS1LRVktTUFSS0VSLW5vdC1hLWtleQ==\n-----END PRIVATE KEY-----\n"
    end = datetime.datetime.now(datetime.timezone.utc) + datetime.timedelta(days=plan.TLS_CERT_DAYS)
    return transport.TlsPair(cert, key, hashlib.sha256(der).hexdigest(), end.strftime("%Y-%m-%dT%H:%M:%SZ"))


def known_hosts_file(directory: Path, key: Tuple[str, bytes] = KEY_A, host: str = ADDRESS) -> Path:
    path = directory / "known_hosts"
    path.write_text(f"{host} {key[0]} {base64.b64encode(key[1]).decode('ascii')}\n", encoding="utf-8")
    return path


@dataclass
class Harness:
    device: FakeDevice
    root: Path
    store: receipt.Store = field(init=False)
    known: Path = field(init=False)
    tls_pairs: List[transport.TlsPair] = field(init=False, default_factory=list)  # every pair made, key kept

    def __post_init__(self) -> None:
        self.store = receipt.Store(self.root / "state")
        self.store.ensure()
        self.known = known_hosts_file(self.root)

    def tls_maker(self, address: str) -> transport.TlsPair:
        """The executor's pair maker: a real one where cryptography works, else ``fixture_tls_pair``; a copy
        with the key is kept here so a test can look for the key in every output."""
        pair = transport.make_tls_pair(address) if cryptography_works() else fixture_tls_pair(address)
        self.tls_pairs.append(
            transport.TlsPair(pair.cert_pem, bytes(pair.key_pem), pair.cert_sha256, pair.not_after)
        )
        return pair

    def executor(
        self,
        console: FakeConsole,
        *,
        netconf_port: Optional[int] = None,
        user: str = USER,
        **run: Any,
    ) -> workstation.Executor:
        target = transport.Target(ADDRESS, user, 22, netconf_port)
        options = workstation.RunOptions(known_hosts=(self.known,), evidence_base=self.root, **run)
        return workstation.Executor(
            target,
            FakeConnector(self.device),
            console,
            self.device.clock,
            self.store,
            options,
            tls_maker=self.tls_maker,
        )

    def factory(
        self,
    ) -> Callable[[transport.Target, workstation.Console, workstation.RunOptions], workstation.Executor]:
        def make(
            target: transport.Target, console: workstation.Console, run: workstation.RunOptions
        ) -> workstation.Executor:
            run = dataclasses.replace(run, known_hosts=(self.known,), evidence_base=self.root)
            return workstation.Executor(
                target,
                FakeConnector(self.device),
                console,
                self.device.clock,
                self.store,
                run,
                tls_maker=self.tls_maker,
            )

        return make


def provenance_ok() -> plan.Provenance:
    return plan.Provenance("release-record", ("v0.1.0.dev1",), True)


def options(**overrides: Any) -> plan.Options:
    """The product's defaults: --access tls on ADDRESS (the --host the harness connects to, an IP literal,
    so the CLI would default to it too). With access 'tunnel', or the lab-token backend (whose default is
    the tunnel), no listen address unless one is given."""
    values: Dict[str, Any] = {"user": USER}
    values.update(overrides)
    access = values.get("access") or ("tunnel" if values.get("backend") == "lab-token" else plan.DEFAULT_ACCESS)
    if access == "tls":
        values.setdefault("listen_address", ADDRESS)
    return plan.Options(**values)


def install(
    harness: Harness,
    data: bytes,
    console: FakeConsole,
    *,
    opts: Optional[plan.Options] = None,
    overrides: Sequence[str] = (),
    **run: Any,
) -> Tuple[int, workstation.Executor]:
    run.setdefault("apply", True)
    executor = harness.executor(console, **run)
    code = executor.install(
        bundle_identity(data), data, provenance_ok(), opts or options(), overrides=frozenset(overrides)
    )
    return code, executor


