@dataclass
class FakeFile:
    data: bytes = b""
    owner: str = USER
    mode: int = 0o644
    is_dir: bool = False
    is_symlink: bool = False  # listed with type 'l' and a target, as 'file list detail' shows a link (inferred)

    @property
    def sha256(self) -> str:
        return hashlib.sha256(self.data).hexdigest()


@dataclass
class Entry:
    user: str
    client: str
    comment: Optional[str]
    confirmed: str  # "" or the commit-confirmed text
    time: datetime.datetime
