class FakeClock:
    def __init__(self, device: FakeDevice) -> None:
        self.device = device
        self.now = 1000.0

    def monotonic(self) -> float:
        return self.now

    def sleep(self, seconds: float) -> None:
        self.now += seconds
        self.device.tick()


