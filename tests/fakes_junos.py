class FakeNetconf:
    def __init__(self, device: FakeDevice, session: int) -> None:
        self.device = device
        self.session = session

    def _alive(self, call: Tuple[Any, ...]) -> None:
        device = self.device
        device.record(call)
        if self.session in device.dead_sessions:
            raise transport.SessionLost("the NETCONF session closed (fake)")
        delay = device.inject.slow_reads.get(str(call[1]) if len(call) > 1 else str(call[0]))
        if delay:
            device.clock.sleep(delay)

    def kill(self) -> None:
        self.device.kill_session(self.session)

    def read(self, name: str, **args: transport.ArgValue) -> transport.Reply:
        transport.check_rpc(name, args, "read")
        self._alive(("rpc", name, dict(args), self.session))
        d = self.device
        if name == "get-software-information":
            return d.software_information()
        if name == "get-chassis-cluster-status":
            return "<rpc-reply><error><message>Chassis cluster is not enabled.</message></error></rpc-reply>"
        if name == "get-chassis-inventory":
            return (
                "<rpc-reply><chassis-inventory><chassis><name>Chassis</name><serial-number>FIXTURE-SN-0001</serial-number>"
                "<chassis-module><name>Routing Engine 0</name></chassis-module></chassis></chassis-inventory>"
                "</rpc-reply>"
            )
        if name == "get-flow-session-information":
            return (
                "<rpc-reply><flow-session-information><flow-session-summary-information>"
                "<active-sessions>12</active-sessions></flow-session-summary-information>"
                "</flow-session-information></rpc-reply>"
            )
        if name == "get-commit-information":
            return d.commit_information()
        if name == "get-rollback-information":
            delta = rollback_delta(d.history, int(str(args["rollback"])), int(str(args["compare"])))
            return (
                "<rpc-reply><rollback-information>"
                f"<configuration-output>{escape(delta)}</configuration-output></rollback-information></rpc-reply>"
            )
        if name == "file-list":
            return d.file_list(str(args["path"]))
        if name == "get-sha256-checksum-information":
            info = d.files.get(str(args["path"]))
            if info is None or info.is_dir:
                return state.RpcErrorReply(f"{args['path']}: No such file or directory")
            return (
                "<rpc-reply><checksum-information><file-checksum><computation-method>SHA256</computation-method>"
                f"<input-file>{escape(str(args['path']))}</input-file><checksum>{info.sha256}</checksum>"
                "</file-checksum></checksum-information></rpc-reply>"
            )
        if name == "file-show":
            info = d.files.get(str(args["filename"]))
            if info is None or info.is_dir:
                return state.RpcErrorReply(f"{args['filename']}: No such file or directory")
            text = escape(info.data.decode("utf-8", "replace"))
            return f'<rpc-reply><file-content filename="x">{text}</file-content></rpc-reply>'
        if name == "jet-application-status":
            return d.status_output()
        raise AssertionError(f"unhandled read {name}")

    def write(self, name: str, **args: transport.ArgValue) -> transport.Reply:
        transport.check_rpc(name, args, "write")
        self._alive(("rpc", name, dict(args), self.session))
        d = self.device
        if name == "file-change-permission":
            path = str(args["filename"])
            if path not in d.files:
                raise transport.DeviceRefused(f"{path}: No such file or directory")
            if d.inject.refuse_chmod:
                raise transport.DeviceRefused(f"error: {path}: Operation not permitted")
            if not d.inject.chmod_ignored:
                d.files[path].mode = int(str(args["permission"]), 8)
            return "<ok/>"
        if name == "file-delete":
            path = str(args["path"])
            if path not in d.files or d.files[path].is_dir:
                raise transport.DeviceRefused(f"error: {path}: No such file or directory")
            if path not in d.inject.keep_on_delete:
                del d.files[path]
            return "<ok/>"
        if name == "file-copy":
            source, destination = str(args["source"]), str(args["destination"])
            if source.startswith(("http://", "https://")):
                data = d.inject.pull_files.get(source)
                if data is None:
                    raise transport.DeviceRefused(f"error: fetch {source} failed")
                mode = 0o644
            else:
                if source not in d.files:
                    raise transport.DeviceRefused(f"error: {source}: No such file or directory")
                data, mode = d.files[source].data, d.files[source].mode
            if destination in d.files and d.inject.refuse_overwrite:
                raise transport.DeviceRefused(f"error: {destination}: File exists")
            d.files[destination] = FakeFile(data, owner=d.inject.copy_owner or d.user, mode=mode)
            return "<ok/>"
        if name == "request-script-refresh-from":
            url = str(args["url"])
            data = d.inject.pull_files.get(url)
            if data is None:
                raise transport.DeviceRefused("error: refresh failed")
            d.files[f"{plan.JET_DIR}/{args['file']}"] = FakeFile(data, owner=d.user, mode=0o644)
            return "<ok/>"
        if name == "extension-service-start":
            return d.start_app(str(args["application-name"]))
        if name == "extension-service-stop":
            if d.daemon is not None and not d.inject.stop_ignored:
                d.daemon = None
            return "<ok/>"
        raise AssertionError(f"unhandled write {name}")

    def get_configuration(self, *, database: str, inherit: bool) -> transport.Reply:
        self._alive(("get-configuration", database, inherit, self.session))
        d = self.device
        model = d.candidate if database == "candidate" else d.committed
        return config_xml(selected(plan.expand_groups(model) if inherit else model))

    def compare(self, rollback: int) -> Optional[str]:
        self._alive(("compare", rollback, self.session))
        d = self.device
        if d.inject.compare_unreadable:
            return None
        if rollback == 0:
            text = plan.patch_text(d.committed, d.candidate)
        else:
            text = d.history[0].delta if d.candidate == d.committed and d.history else ""
        return (text + d.inject.compare_extra) or None

    def lock(self) -> None:
        self._alive(("lock", self.session))
        d = self.device
        if d.lock_owner is not None and d.lock_owner != self.session:
            raise transport.DeviceRefused("configuration database locked by otheradmin")
        if d.candidate != d.committed:
            raise transport.DeviceRefused("configuration database modified")
        d.lock_owner = self.session

    def unlock(self) -> None:
        self._alive(("unlock", self.session))
        d = self.device
        if d.lock_owner == self.session:
            d.lock_owner = None
            d.candidate = d.committed

    def load_set(self, lines: Sequence[str]) -> None:
        self._alive(("load", tuple(lines), self.session))
        d = self.device
        if d.lock_owner != self.session:
            raise transport.DeviceRefused("not locked")
        for line in lines:
            if not line.startswith(("set ", "delete ")):
                raise transport.DeviceRefused(f"syntax error: {line}")
        d.candidate = plan.apply_lines(d.candidate, [*lines, *d.inject.load_extra])

    def discard(self) -> None:
        self._alive(("discard", self.session))
        self.device.candidate = self.device.committed

    def load_rollback(self, number: int) -> None:
        self._alive(("load-rollback", number, self.session))
        d = self.device
        previous = d.pending.previous if d.pending is not None else d.committed
        d.candidate = previous

    def commit(self, comment: str, confirm: Optional[plan.Minutes]) -> None:
        self._alive(("commit", comment, None if confirm is None else int(confirm), self.session))
        d = self.device
        if d.lock_owner != self.session:
            raise transport.DeviceRefused("not locked")
        extra: Tuple[str, ...] = ()
        if confirm is not None:
            extra, d.inject.commit_extra = d.inject.commit_extra, ()
        d.commit_model(
            plan.apply_lines(d.candidate, extra),
            user=d.user,
            client="netconf",
            comment=comment,
            confirm=None if confirm is None else int(confirm),
            session=self.session,
        )

    def close(self) -> None:
        self.device.calls.append(("close", self.session))
        if self.session not in self.device.dead_sessions:
            self.kill()


class FakeSsh:
    def __init__(self, device: FakeDevice) -> None:
        self.device = device

    def put(self, data: bytes, path: str, mode: int) -> None:
        d = self.device
        d.record(("scp-put", path, mode))
        parent = path.rpartition("/")[0]
        if parent not in d.files:
            raise transport.DeviceRefused(f"scp: {path}: No such file or directory")
        existing = d.files.get(path)
        if existing is not None:
            existing.data = data  # an existing file keeps its mode (inferred scp behaviour)
            return
        new_mode = d.inject.scp_mode if d.inject.scp_mode is not None else mode & ~0o022
        d.files[path] = FakeFile(data, owner=d.inject.scp_owner or d.user, mode=new_mode)

    def get(self, path: str, local_path: str) -> None:
        d = self.device
        d.record(("scp-get", path))
        if path not in d.files:
            raise transport.DeviceRefused(f"scp: {path}: No such file or directory")
        Path(local_path).write_bytes(d.files[path].data)
        d.local_files[local_path] = d.files[path].data

    def veriexec(self) -> Optional[str]:
        self.device.record(("veriexec",))
        return self.device.veriexec

    def close(self) -> None:
        self.device.calls.append(("ssh-close",))


class FakeConnector:
    def __init__(self, device: FakeDevice) -> None:
        self.device = device
        self.ssh_configs: List[str] = []

    def host_key(self, port: int, key_types: Sequence[str]) -> Tuple[str, bytes]:
        self.device.record(("host-key", port))
        key = self.device.host_keys.get(port)
        if key is None:
            raise transport.TransportError(f"TCP to port {port} refused (fake)")
        return key

    def open_ssh(self, key: Tuple[str, bytes], key_types: Sequence[str]) -> transport.Ssh:
        self.device.record(("ssh-open",))
        return FakeSsh(self.device)

    def netconf_available(self, ssh: transport.Ssh, key: Tuple[str, bytes]) -> bool:
        return self.device.netconf_on()

    def open_netconf(self, ssh_config: str) -> transport.Netconf:
        self.ssh_configs.append(Path(ssh_config).read_text(encoding="utf-8"))
        d = self.device
        d.record(("netconf-open",))
        if d.inject.netconf_key_rejected:
            raise transport.HostKeyRejected("NETCONF on port 22 presented a host key other than the one verified")
        if not d.netconf_on():
            raise transport.NetconfUnavailable("NETCONF refused (fake)")
        d.sessions += 1
        return FakeNetconf(d, d.sessions)

    def https_get(self, address: str, port: int, path: str, host_header: str, pin_sha256: str) -> transport.HttpsResult:
        """C8's read of the fake listener, as transport.https_get makes it: the certificate is compared with
        the pin before the request is 'sent', and the daemon answers 421 to a Host it does not allow."""
        d = self.device
        d.record(("https-get", address, port, host_header, path))
        where = plan.host_port(address, port)
        if d.inject.https_timeout:
            d.clock.sleep(float(plan.TIMEOUTS["http"]))
            return transport.HttpsResult(False, reason=f"TLS with {where} failed: timed out (fake)")
        daemon = d.daemon
        if d.inject.https_refused or daemon is None or not daemon.tls or (daemon.bind, daemon.port) != (address, port):
            return transport.HttpsResult(False, reason=f"TCP to {where} failed: Connection refused (fake)")
        presented = OTHER_CERT if d.inject.https_other_cert else daemon.cert_sha256
        if presented != pin_sha256:
            return transport.HttpsResult(
                True,
                False,
                reason="the certificate presented is not the one this installer made",
                peer_sha256=presented,
            )
        d.calls.append(("https-request", path, host_header))
        if host_header not in daemon.allowed_hosts:
            return transport.HttpsResult(True, True, b"HTTP/1.1 421 Misdirected Request\r\n\r\n", peer_sha256=presented)
        session: Dict[str, Any] = {"authenticated": False, "version": daemon.version}
        if daemon.build is not None:
            session["build"] = daemon.build
        body = json.dumps(session)
        response = f"HTTP/1.1 200 OK\r\nContent-Type: application/json\r\nContent-Length: {len(body)}\r\n\r\n{body}"
        return transport.HttpsResult(True, True, response.encode("ascii"), peer_sha256=presented)


class FakeConsole(workstation.Console):
    """A terminal with scripted answers; every prompt and gate is recorded in the device's call log."""

    def __init__(
        self,
        device: FakeDevice,
        answers: Sequence[str] = (),
        *,
        interactive: bool = True,
        json_mode: bool = False,
        stdin_text: str = "",
    ) -> None:
        self.out = io.StringIO()
        self.err = io.StringIO()
        super().__init__(json_mode=json_mode, stdin=io.StringIO(stdin_text), stdout=self.out, stderr=self.err)
        self.device = device
        self.answers = list(answers)
        self._interactive = interactive
        self.prompts: List[str] = []

    @property
    def interactive(self) -> bool:
        return self._interactive

    def prompt(self, text: str) -> Optional[str]:
        self.prompts.append(text)
        if text == plan.LAB_GATE_PROMPT:
            self.device.calls.append(("gate",))
        elif text == plan.LAB_HARDWARE_PROMPT:
            self.device.calls.append(("lab-only",))
        else:
            self.device.calls.append(("prompt", text))
        if not self._interactive:
            return None
        return self.answers.pop(0) if self.answers else ""

    def stdin_line(self, what: str = "gate") -> Optional[str]:
        self.device.calls.append((what,))
        return super().stdin_line(what)

    def text(self) -> str:
        return self.out.getvalue() + self.err.getvalue()


