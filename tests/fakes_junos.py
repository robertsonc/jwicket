"""Recording fakes of a lab vSRX (or the lab SRX4100) for the installer tests (Spec 006, AC-006-13 to
AC-006-30).

Nothing here talks to a device, and nothing here proves what a device does: the fakes encode the
installer's reading of Junos (every reply shape is synthetic, shaped like tests/fixtures/install/; the
real ones are recorded by lab test Q-INST-01). What they do give is a model that keeps state across a
run (configuration, commit history with deltas, a pending confirmed commit with its deadline, files with
owners and modes, a daemon that starts when its stanza, files and settings allow it), records every call
in order, and can inject the adversarial events of AC-006-15, -16 and -28: foreign pending, scheduled and
prepared commits, lock and session loss, stale result files, restart loops, refused overwrites, a
listener that is refused, times out or presents another certificate, and different host keys per port.

What the lab run verified on SRX4100 25.2R1-S1.4 (docs/evidence/2026-11-24-srx4100-lab), the daemon
model follows: /var/db/jwicket is made by root (the base device has it, trusted and empty; nothing here
creates a directory, because no directory RPC is in ``INSTALL_RPCS``); with 'system management-instance'
a listener on a management address starts only with ``routing_instance = mgmt_junos`` ("Can't assign
requested address" otherwise); off loopback the daemon needs its TLS pair, owned by its account, the key
private. The listener answers C8's HTTPS read with the certificate it loaded (``FakeConnector.https_get``):
no SSH channel exists in these fakes, as none exists in the installer (revision R3).

``FakeNetconf`` and ``FakeSsh`` implement ``jwicket_install.transport.Netconf`` and ``Ssh``; every RPC
goes through ``transport.check_rpc``, so a name or argument outside ``INSTALL_RPCS`` fails the test.
"""

