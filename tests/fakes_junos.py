def config_xml(model: StatementSet) -> str:
    import xml.etree.ElementTree as ET

    root = ET.Element("configuration")

    def child(node: ET.Element, tag: str, name: Optional[str] = None) -> ET.Element:
        for existing in node:
            if existing.tag != tag:
                continue
            if name is None:
                if existing.find("name") is None:
                    return existing
            else:
                found = existing.find("name")
                if found is not None and found.text == name:
                    return existing
        made = ET.SubElement(node, tag)
        if name is not None:
            ET.SubElement(made, "name").text = name
        return made

    for key, value in sorted(model.pairs):
        tokens = key.split(" ")
        if tokens == ["apply-groups"]:
            ET.SubElement(root, "apply-groups").text = value
            continue
        node = root
        index = 0
        while index < len(tokens):
            token = tokens[index]
            is_last = index == len(tokens) - 1
            if token in LIST_PARENTS and not is_last:
                node = child(node, token, tokens[index + 1])
                index += 2
                continue
            if is_last:
                leaf = child(node, token)
                if value:
                    leaf.text = value
            else:
                node = child(node, token)
            index += 1
    return (
        "<rpc-reply><configuration>"
        + "".join(ET.tostring(c, encoding="unicode") for c in root)
        + "</configuration></rpc-reply>"
    )


def selected(model: StatementSet) -> StatementSet:
    """What a select-only read (transport.CONFIG_FILTER) returns of ``model``: only the subtrees the filter
    names (state.WALKED, groups jwicket, apply-groups). A statement outside them, such as 'system login',
    is never in a configuration read, so only the text diff can show it (spec 8.7)."""
    prefixes = [" ".join(sub) for sub in state.WALKED] + [" ".join(plan.GROUP_PREFIX), "apply-groups"]
    return StatementSet.of(
        {pair for pair in model.pairs if any(pair[0] == pre or pair[0].startswith(pre + " ") for pre in prefixes)}
    )


def invert_patch(text: str) -> str:
    """The patch read the other way round: '+' and '-' swap."""
    swap = {"+": "-", "-": "+"}
    return "".join(swap[line[0]] + line[1:] if line[:1] in swap else line for line in text.splitlines(True))


def rollback_delta(history: Sequence[Any], rollback: int, compare: int) -> str:
    """get-rollback-information as the NETCONF guide documents it ([netconf-pdf], verified): <rollback> is
    the base, and '+' is what adding to the base gives the <compare> configuration. ``history[n].delta``
    is what commit n added ('+') and removed ('-'), so base n+1 compared with n is that delta, and the
    reversed order (base n, compare n+1) is its inverse. Only adjacent entries are ever asked for."""
    if rollback == compare + 1:
        return str(history[compare].delta) if compare < len(history) else ""
    if compare == rollback + 1:
        return invert_patch(str(history[rollback].delta)) if rollback < len(history) else ""
    raise AssertionError(f"get-rollback-information of non-adjacent entries {rollback} and {compare}")


