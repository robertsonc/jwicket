def make_bundle(
    version: str = "0.1.0.dev1",
    *,
    payload: str = "2e" * 32,
    features: Sequence[str] = ("build-line", "result-files"),
    filler: str = "",
) -> bytes:
    """A synthetic bundle with tools/bundle.py's header lines (it never runs)."""
    header = (
        "#!/usr/bin/env python3\n"
        '"""J-Wicket single-file bundle. GENERATED by tools/bundle.py: DO NOT EDIT; rebuild instead.\n\n'
        f"jwicket version: {version}\n"
        f"source ref:      {'a1' * 20}\n"
        f"payload sha256:  {payload}\n"
        + (f"features:        {','.join(features)}\n" if features else "")
        + 'contents:        1 modules, 0 static files\n"""\n'
    )
    return (header + "# synthetic test bundle " + filler + "\n").encode("utf-8")


def bundle_identity(data: bytes) -> plan.BundleId:
    return plan.BundleId.from_header(data[:4096].decode("utf-8"), hashlib.sha256(data).hexdigest(), len(data))


