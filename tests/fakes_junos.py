class FakeDevice:
    """One lab vSRX: committed and candidate configuration, history, files, a daemon, injections."""

    def __init__(
        self,
        *,
        hostname: Optional[str] = HOST,
        model: str = "vsrx",
        release: str = "24.4R2-S3.5",
        netconf: bool = True,
        config: Iterable[Tuple[str, str]] = (),
        veriexec: str = "security.mac.veriexec.state: loaded active enforce",
        host_keys: Optional[Mapping[int, Tuple[str, bytes]]] = None,
        user: str = USER,
        state_dir: bool = True,
    ) -> None:
        self.clock = FakeClock(self)
        self.calls: List[Tuple[Any, ...]] = []
        pairs = set(config)
        if netconf:
            pairs.add(NETCONF_PAIR)
        self.committed = StatementSet.of(pairs)
        self.candidate = self.committed
        self.hostname = hostname
        self.model = model
        self.release = release
        self.veriexec = veriexec
        self.user = user
        self.history: List[Entry] = [
            Entry("admin", "cli", "initial lab build", "", BASE_TIME - datetime.timedelta(days=5), ""),
            Entry("admin", "cli", None, "", BASE_TIME - datetime.timedelta(days=4), ""),
        ][::-1]
        self.pending: Optional[PendingCommit] = None
        self.scheduled = False
        self.prepared = False
        self.lock_owner: Optional[int] = None
        self.files: Dict[str, FakeFile] = {
            "/var/db": FakeFile(owner="root", mode=0o755, is_dir=True),
            "/var/db/scripts": FakeFile(owner="root", mode=0o775, is_dir=True),
            plan.JET_DIR: FakeFile(owner="root", mode=0o775, is_dir=True),
            plan.OP_DIR: FakeFile(owner="root", mode=0o775, is_dir=True),
            f"{plan.JET_DIR}/nc_grpc_app": FakeFile(b"binary", owner="root", mode=0o755),
        }
        if state_dir:  # made once by root and given to the account (R4, verified on SRX4100)
            self.files[plan.STATE_DIR] = FakeFile(owner=user, mode=0o700, is_dir=True)
        self.daemon: Optional[Daemon] = None
        self.next_pid = 4242
        self.inject = Injections()
        self.host_keys: Dict[int, Tuple[str, bytes]] = dict(host_keys or {22: KEY_A, 830: KEY_A})
        self.sessions = 0
        self.dead_sessions: Set[int] = set()
        self.hooks: List[Tuple[Callable[[Tuple[Any, ...]], bool], Callable[[FakeDevice], None], List[bool]]] = []
        self.confirmed_foreign = False
        self.local_files: Dict[str, bytes] = {}

    # -- time ----------------------------------------------------------------------------------------

    def device_time(self) -> datetime.datetime:
        return BASE_TIME + datetime.timedelta(seconds=self.clock.now - 1000.0)

    def stamp(self) -> str:
        return self.device_time().strftime("%Y-%m-%d %H:%M:%S") + ",000"

    def tick(self) -> None:
        if self.pending is not None and self.clock.now >= self.pending.deadline:
            self.rollback_pending("deadline")

    def rollback_pending(self, why: str) -> None:
        pending = self.pending
        if pending is None:
            return
        self.calls.append(("device-rollback", why))
        before = self.committed
        self.committed = pending.previous
        if self.lock_owner is None or self.candidate == before:
            self.candidate = self.committed
        pending.entry.confirmed = ""
        self._entry("root", "junos", None, plan.patch_text(before, self.committed))
        self.pending = None
        self.reconcile()

    def kill_session(self, session: int) -> None:
        """A dropped session: Junos restores a pending confirmed commit it issued (documented for
        kill-session; inferred for a drop, Q-INST-03), and the lock goes with it."""
        self.dead_sessions.add(session)
        if self.lock_owner == session:
            self.lock_owner = None
            self.candidate = self.committed
        if self.pending is not None and self.pending.session == session and self.inject.drop_rollback_at_once:
            self.rollback_pending("session ended")

    def drop_latest(self) -> None:
        self.kill_session(self.sessions)

    # -- hooks ---------------------------------------------------------------------------------------

    def on(
        self, match: Callable[[Tuple[Any, ...]], bool], action: Callable[[FakeDevice], None], *, once: bool = True
    ) -> None:
        """Run ``action`` just before the first call (or every call) that ``match`` accepts."""
        self.hooks.append((match, action, [once]))

    def record(self, call: Tuple[Any, ...]) -> None:
        for match, action, flags in list(self.hooks):
            if match(call):
                if flags[0]:
                    self.hooks.remove((match, action, flags))
                action(self)
        self.calls.append(call)

    # -- history -------------------------------------------------------------------------------------

    def _entry(self, user: str, client: str, comment: Optional[str], delta: str, confirmed: str = "") -> Entry:
        entry = Entry(user, client, comment, confirmed, self.device_time(), delta)
        self.history.insert(0, entry)
        return entry

    def commit_model(
        self, new: StatementSet, *, user: str, client: str, comment: Optional[str], confirm: Optional[int], session: int
    ) -> None:
        if self.inject.refuse_commit:
            raise transport.DeviceRefused(self.inject.refuse_commit)
        if self.pending is not None:
            if self.pending.session != session and self.pending.entry.user != user:
                self.confirmed_foreign = True
            self.pending.entry.confirmed = ""
            self.pending = None
        before = self.committed
        self.committed = new
        self.candidate = new
        entry = self._entry(
            user,
            client,
            comment,
            plan.patch_text(before, new),
            f"commit confirmed, rollback in {confirm}mins" if confirm else "",
        )
        if confirm:
            self.pending = PendingCommit(self.clock.now + confirm * 60, before, session, entry)
        self.reconcile()

    def cli_commit(
        self, lines: Sequence[str], comment: str, *, confirm: Optional[int] = None, user: str = USER
    ) -> None:
        """An operator's or another administrator's CLI commit (session 0)."""
        self.commit_model(
            plan.apply_lines(self.committed, lines),
            user=user,
            client="cli",
            comment=comment,
            confirm=confirm,
            session=0,
        )

    def foreign_commit(self, *, confirmed: bool) -> None:
        self.cli_commit(["set system ntp server"], "maintenance", confirm=10 if confirmed else None, user="otheradmin")

    def effective(self) -> StatementSet:
        return plan.expand_groups(self.committed)

    # -- the daemon ----------------------------------------------------------------------------------

    def _settings(self) -> Dict[str, str]:
        """The 'key = value' lines of jwicket.ini (the daemon's own parser is jwicket.settings)."""
        text = self.files.get(plan.SETTINGS_PATH, FakeFile()).data.decode("utf-8", "replace")
        values: Dict[str, str] = {}
        for line in text.splitlines():
            match = re.match(r"^([a-z_]+) = (.*)$", line)
            if match:
                values[match.group(1)] = match.group(2).strip()
        return values

    def _start_problem(self, values: Mapping[str, str], eff: StatementSet) -> Tuple[Optional[str], Optional[str]]:
        """Why the daemon would refuse to start with these settings (settings.py's rules and the SRX4100
        lab's management-instance fact), and the SHA-256 of the certificate it would load."""
        bind = values.get("bind", plan.LOOPBACK)
        tls = "tls_cert" in values and "tls_key" in values
        if bind != plan.LOOPBACK and not tls:
            return f"bind = {bind} is not a loopback address, so TLS is required", None
        cert_sha: Optional[str] = None
        if tls:
            cert, key = self.files.get(values["tls_cert"]), self.files.get(values["tls_key"])
            if cert is None or key is None:
                return "TLS certificate or private key: No such file or directory", None
            if cert.owner != self.user or key.owner != self.user:
                return "TLS certificate or private key is owned by another account", None
            if key.mode & 0o077:
                return "TLS private key is readable or writable by group or other", None
            cert_sha = transport.pem_certificate_sha256(cert.data)
            if cert_sha is None:
                return "TLS certificate is not a PEM certificate", None
        if (
            eff.has(plan.MANAGEMENT_INSTANCE_KEY, "")
            and bind != plan.LOOPBACK
            and values.get("routing_instance") != plan.MGMT_INSTANCE
        ):
            # Verified on SRX4100 25.2R1-S1.4: fxp0's address cannot be bound from the default instance.
            return f"cannot listen on {bind}: Can't assign requested address", None
        return None, cert_sha

    def reconcile(self) -> None:
        eff = self.effective()
        app = " ".join(plan.STANZA_KEYS["F-DAEMON"])
        stanza = frozenset(eff.under(app))
        file = self.files.get(plan.DAEMON_PATH)
        settings = self.files.get(plan.SETTINGS_PATH)
        pinned = eff.values(app + " checksum sha-256")
        want = (
            (app + " daemonize", "") in stanza
            and file is not None
            and settings is not None
            and (not pinned or pinned == (file.sha256,))
            and eff.has("system scripts language", "python3")
        )
        if not want:
            if self.daemon is not None and not self.inject.stop_ignored:
                self.calls.append(("daemon-stop", self.daemon.pid))
                self.daemon = None
            return
        assert file is not None and settings is not None
        values = self._settings()
        tls_files = tuple(
            self.files[p].sha256 if p in self.files else "" for p in (plan.TLS_CERT_PATH, plan.TLS_KEY_PATH)
        )
        identity = (file.sha256, settings.sha256, stanza, tls_files, (plan.MANAGEMENT_INSTANCE_KEY, "") in eff.pairs)
        if self.daemon is not None and self.daemon.identity == identity:
            return
        problem, cert_sha = self._start_problem(values, eff)
        if self.inject.refuse_start:
            problem = "settings check failed"
        if problem is not None:
            self._append(plan.STARTUP_REFUSED_PATH, f"jwicket: refused to start: {problem}\n".encode(), replace=True)
            self.daemon = None
            return
        bundle = bundle_identity(file.data)
        port = int(values.get("port", str(plan.DEFAULT_PORT)))
        backend = values.get("backend", "netconf")
        bind = values.get("bind", plan.LOOPBACK)
        tls = cert_sha is not None
        instance = values.get("routing_instance") or "default"
        starts = 2 if self.inject.restart_loop else 1
        for _ in range(starts):
            self.next_pid += 1
            # app.py's start line (tests/test_routing_instance.py and the DAEMON contract test keep the form).
            line = f"{self.stamp()} INFO jwicket listening on {bind}:{port} tls={tls} backend={backend}"
            if bundle.has("build-line"):
                line += f" routing_instance={instance} version={bundle.version} payload={bundle.payload_short}"
            self._append(plan.LOG_PATH, (line + "\n").encode("ascii"))
            record: Dict[str, Any] = {
                "event": "start",
                "source": "local",
                "ts": "x",
                "user": None,
                "version": bundle.version,
            }
            if bundle.has("build-line"):
                record["payload_sha256"] = bundle.payload_sha256
            self._append(plan.AUDIT_PATH, (json.dumps(record, sort_keys=True) + "\n").encode("ascii"))
        hosts = tuple(h.strip() for h in values.get("allowed_hosts", "").split(",") if h.strip())
        self.daemon = Daemon(
            self.next_pid,
            bundle.version,
            bundle.payload_sha256,
            port,
            backend,
            identity,
            bind=bind,
            tls=tls,
            cert_sha256=cert_sha,
            allowed_hosts=hosts,
            build=bundle.payload_short if bundle.has("build-line") else None,
        )
        self.calls.append(("daemon-start", self.next_pid))

    def _append(self, path: str, data: bytes, *, replace: bool = False) -> None:
        if plan.STATE_DIR not in self.files:
            return
        existing = self.files.get(path)
        if existing is None or replace:
            self.files[path] = FakeFile(data, owner=self.user, mode=0o600)
        else:
            existing.data += data

    def stanza_configured(self, app: str) -> bool:
        return bool(self.effective().under(" ".join((*plan.STANZA_KEYS["F-SELFTEST"][:-1], app))))

    # -- replies -------------------------------------------------------------------------------------

    def software_information(self) -> str:
        host = f"<host-name>{self.hostname}</host-name>" if self.hostname else ""
        return (
            "<rpc-reply><software-information>"
            f"{host}<product-model>{self.model}</product-model><product-name>{self.model}</product-name>"
            f"<junos-version>{self.release}</junos-version></software-information></rpc-reply>"
        )

    def commit_information(self) -> str:
        parts = ["<rpc-reply><commit-information>"]
        if self.scheduled:
            parts.append("<pending-commit><commit-at>2026-11-25 03:00:00 UTC</commit-at></pending-commit>")
        if self.prepared:
            parts.append("<prepared-commit><prepared-by>otheradmin</prepared-by></prepared-commit>")
        for index, entry in enumerate(self.history[:50]):
            parts.append("<commit-history>")
            parts.append(f"<sequence-number>{index}</sequence-number>")
            parts.append(f"<date-time>{entry.time.strftime('%Y-%m-%d %H:%M:%S')} UTC</date-time>")
            parts.append(f"<user>{escape(entry.user)}</user><client>{escape(entry.client)}</client>")
            if entry.comment:
                parts.append(f"<comment>{escape(entry.comment)}</comment>")
            if entry.log:
                parts.append(f"<log>{escape(entry.log)}</log>")
            if entry.confirmed:
                parts.append(f"<commit-confirmed>{escape(entry.confirmed)}</commit-confirmed>")
            parts.append("</commit-history>")
        parts.append("</commit-information></rpc-reply>")
        return "".join(parts)

    def file_list(self, path: str) -> str:
        info = self.files.get(path)
        if info is None or not info.is_dir:
            return (
                "<rpc-reply><directory-list>"
                f"<output>{escape(path)}: No such file or directory</output></directory-list></rpc-reply>"
            )
        parts = [f"<rpc-reply><directory-list><directory><directory-name>{escape(path)}</directory-name>"]
        for name, entry in sorted(self.files.items()):
            parent, _, base = name.rpartition("/")
            if parent != path:
                continue
            kind = "l" if entry.is_symlink else ("d" if entry.is_dir else "-")
            perms = "".join(ch if entry.mode & (1 << (8 - i)) else "-" for i, ch in enumerate("rwxrwxrwx"))
            parts.append(
                "<file-information>"
                f"<file-name>{escape(base)}</file-name>"
                + ("<file-directory/>" if entry.is_dir and not entry.is_symlink else "")
                + ("<file-symlink-target>/tmp/elsewhere</file-symlink-target>" if entry.is_symlink else "")
                + f'<file-permissions format="{kind}{perms}">{entry.mode:o}</file-permissions>'
                f"<file-owner>{escape(entry.owner)}</file-owner><file-group>wheel</file-group>"
                f"<file-size>{len(entry.data) if not entry.is_dir else 512}</file-size>"
                "</file-information>"
            )
        parts.append("</directory></directory-list></rpc-reply>")
        return "".join(parts)

    def status_output(self) -> str:
        if self.daemon is None:
            return "<rpc-reply><output>warning: No active extension-services</output></rpc-reply>"
        if self.inject.pid_changes:
            self.daemon.pid += 1
        return (
            "<rpc-reply><output>Extension service application details:\n"
            f"Name : jwicket.py\nProcess-id: {self.daemon.pid}\nStack-Segment-Size: 16777216\n</output></rpc-reply>"
        )

    def start_app(self, app: str) -> str:
        path = f"{plan.JET_DIR}/{app}"
        if not self.stanza_configured(app) or path not in self.files:
            raise transport.DeviceRefused(f"error: application {app} is not configured")
        bundle = bundle_identity(self.files[path].data)
        if app == plan.SELFTEST_FILE:
            body: Dict[str, Any] = {
                "bundle": "jwicket",
                "version": bundle.version,
                "payload_sha256": bundle.payload_sha256,
                "ok": True,
                "failures": [],
            }
            result = plan.SELFTEST_RESULT_PATH
        else:
            modules = {
                m: "ok"
                for m in (
                    "http.server",
                    "ssl",
                    "json",
                    "hmac",
                    "threading",
                    "jnpr.junos",
                    "lxml",
                    "ncclient",
                    "paramiko",
                )
            }
            for missing in self.inject.probe_missing:
                modules[missing] = f"missing: No module named {missing!r}"
            body = {"jwicket": bundle.version, "python": "3.7.10", "modules": modules}  # as on SRX4100
            result = plan.PROBE_RESULT_PATH
        text = json.dumps(body, indent=2, sort_keys=True) + "\n"
        directory = self.files.get(plan.STATE_DIR)
        if (
            bundle.has("result-files")
            and directory is not None
            and directory.owner == self.user
            and not directory.mode & 0o022
        ):
            self.files[result] = FakeFile(text.encode("ascii"), owner=self.user, mode=0o600)
        if self.inject.start_output:
            return f"<rpc-reply><output>{escape(text)}</output></rpc-reply>"
        return "<rpc-reply><ok/></rpc-reply>"

    # -- connections ---------------------------------------------------------------------------------

    def netconf_on(self) -> bool:
        return bool(self.effective().under("system services netconf ssh"))

    def writes_before(self, marker: str = "gate") -> List[Tuple[Any, ...]]:
        """Every write recorded before the first ``marker`` call (INV-01)."""
        out = []
        for call in self.calls:
            if call[0] == marker:
                break
            if call[0] in WRITES or (call[0] == "rpc" and call[1] in transport.WRITE_RPCS):
                out.append(call)
        return out

    def names(self) -> List[str]:
        return [c[1] if c[0] == "rpc" else c[0] for c in self.calls]

    def plain_files(self) -> Dict[str, Tuple[str, str, int]]:
        return {p: (f.sha256, f.owner, f.mode) for p, f in self.files.items()}


