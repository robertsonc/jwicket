def settings_of(data: bytes) -> Dict[str, str]:
    """The key = value lines of a jwicket.ini (section names dropped: the keys the fake reads are unique)."""
    out: Dict[str, str] = {}
    for line in data.decode("utf-8", "replace").splitlines():
        key, sep, value = line.partition("=")
        if sep and not line.lstrip().startswith(("#", ";", "[")):
            out[key.strip()] = value.strip()
    return out


class FakeClock:
    def __init__(self, box: FakeBox) -> None:
        self.box = box
        self.now = 1000.0

    def monotonic(self) -> float:
        return self.now

    def sleep(self, seconds: float) -> None:
        self.now += seconds
        self.box.tick()


class FakeBox:
    """One lab vSRX as the op script sees it through on-box PyEZ."""

    def __init__(
        self,
        *,
        config: Iterable[Tuple[str, str]] = (),
        hostname: Optional[str] = HOST,
        model: str = "vsrx",
        release: str = "24.4R2-S3.5",
        state_dir: bool = True,
        tls_pair: bool = True,
    ) -> None:
        self.clock = FakeClock(self)
        self.calls: List[Tuple[Any, ...]] = []
        self.committed = StatementSet.of(config)
        self.original = self.committed
        self.candidate = self.committed
        self.hostname = hostname
        self.model = model
        self.release = release
        self.history: List[Entry] = [
            Entry("admin", "cli", None, "", BASE_TIME - datetime.timedelta(days=4), ""),
            Entry("admin", "cli", "initial lab build", "", BASE_TIME - datetime.timedelta(days=5), ""),
        ]
        self.pending: Optional[PendingCommit] = None
        self.lock_owner: Optional[int] = None
        self.sessions = 0
        self.dead_sessions: set = set()
        self.files: Dict[str, FakeFile] = {
            "/var/db": FakeFile(owner="root", mode=0o755, is_dir=True),
            "/var/db/scripts": FakeFile(owner="root", mode=0o775, is_dir=True),
            plan.JET_DIR: FakeFile(owner="root", mode=0o775, is_dir=True),
            plan.OP_DIR: FakeFile(owner="root", mode=0o775, is_dir=True),
            plan.OP_PATH: FakeFile(b"# the op script\n", owner=USER, mode=0o644),
            "/var/home": FakeFile(owner="root", mode=0o755, is_dir=True),
            HOME: FakeFile(owner=USER, mode=0o755, is_dir=True),
        }
        if state_dir:  # R4: made once by root ('mkdir -m 700 ... && chown <user> ...'), then the account's
            self.files[plan.STATE_DIR] = FakeFile(owner=USER, mode=0o700, is_dir=True)
            if tls_pair:  # R2 on the box: the operator's pair, made in the shell as the account
                self.files[plan.TLS_KEY_PATH] = FakeFile(KEY_PEM, owner=USER, mode=plan.TLS_KEY_MODE)
                self.files[plan.TLS_CERT_PATH] = FakeFile(CERT_PEM, owner=USER, mode=plan.TLS_CERT_MODE)
        self.daemon: Optional[Daemon] = None
        self.next_pid = 4242
        self.inject = Injections()
        self.hooks: List[Tuple[Callable[[Tuple[Any, ...]], bool], Callable[[FakeBox], None]]] = []

    # -- time and hooks ------------------------------------------------------------------------------

    def device_time(self) -> datetime.datetime:
        return BASE_TIME + datetime.timedelta(seconds=self.clock.now - 1000.0)

    def tick(self) -> None:
        if self.pending is not None and self.clock.now >= self.pending.deadline:
            self.rollback_pending()

    def on(self, match: Callable[[Tuple[Any, ...]], bool], action: Callable[[FakeBox], None]) -> None:
        """Run ``action`` once, just before the first call that ``match`` accepts."""
        self.hooks.append((match, action))

    def record(self, call: Tuple[Any, ...]) -> None:
        for match, action in list(self.hooks):
            if match(call):
                self.hooks.remove((match, action))
                action(self)
        self.calls.append(call)

    # -- commits ---------------------------------------------------------------------------------------

    def _entry(self, user: str, client: str, comment: Optional[str], delta: str, confirmed: str = "") -> Entry:
        entry = Entry(user, client, comment, confirmed, self.device_time(), delta)
        self.history.insert(0, entry)
        return entry

    def rollback_pending(self) -> None:
        pending = self.pending
        if pending is None:
            return
        before = self.committed
        self.committed = pending.previous
        if self.lock_owner is None or self.candidate == before:
            self.candidate = self.committed
        pending.entry.confirmed = ""
        self._entry("root", "junos", None, plan.patch_text(before, self.committed))
        self.pending = None
        self.calls.append(("device-rollback",))
        self.reconcile()

    def commit_model(
        self, new: StatementSet, *, user: str, client: str, comment: Optional[str], confirm: Optional[int], session: int
    ) -> None:
        if self.pending is not None:
            self.pending.entry.confirmed = ""
            self.pending = None
        before = self.committed
        self.committed = new
        self.candidate = new
        entry = self._entry(
            user,
            client,
            comment,
            plan.patch_text(before, new),
            f"commit confirmed, rollback in {confirm}mins" if confirm else "",
        )
        if confirm:
            self.pending = PendingCommit(self.clock.now + confirm * 60, before, session, entry)
        self.reconcile()

    def cli_commit(
        self, lines: Sequence[str], comment: str, *, confirm: Optional[int] = None, user: str = USER
    ) -> None:
        """An operator's or another administrator's CLI commit (session 0)."""
        self.commit_model(
            plan.apply_lines(self.committed, lines),
            user=user,
            client="cli",
            comment=comment,
            confirm=confirm,
            session=0,
        )

    def paste_bootstrap(
        self, method: Method = Method.ONBOX_LOCAL, *, user: str = USER, extra: Sequence[str] = ()
    ) -> plan.Bootstrap:
        """The operator pastes unit A (spec 6.5 step 2 or 6.6): unconfirmed, 10 minutes."""
        prior = plan.PriorState(effective=self.committed, direct=self.committed)
        boot = plan.build_bootstrap(method, plan.Options(user=USER), prior, None, op_sha256=OP_SHA)
        assert boot is not None
        stage = plan.Stage("bootstrap", boot.add, (), (), boot.comment, boot.confirm_comment, plan.Minutes(10), ())
        self.cli_commit([*plan.stage_lines(stage, Layout.DIRECT), *extra], boot.comment, confirm=10, user=user)
        return boot

    def foreign_commit(self, *, confirmed: bool) -> None:
        self.cli_commit(["set system ntp server"], "maintenance", confirm=10 if confirmed else None, user=OTHER)

    def effective(self) -> StatementSet:
        return plan.expand_groups(self.committed)

    # -- the daemon ------------------------------------------------------------------------------------

    def reconcile(self) -> None:
        eff = self.effective()
        app = " ".join(plan.STANZA_KEYS["F-DAEMON"])
        stanza = frozenset(eff.under(app))
        file = self.files.get(plan.DAEMON_PATH)
        settings = self.files.get(plan.SETTINGS_PATH)
        pinned = eff.values(app + " checksum sha-256")
        want = (
            (app + " daemonize", "") in stanza
            and file is not None
            and settings is not None
            and (not pinned or pinned == (file.sha256,))
            and eff.has("system scripts language", "python3")
        )
        if not want:
            if self.daemon is not None and not self.inject.stop_ignored:
                self.calls.append(("daemon-stop", self.daemon.pid))
                self.daemon = None
            return
        assert file is not None and settings is not None
        identity = (file.sha256, settings.sha256, stanza)
        if self.daemon is not None and self.daemon.identity == identity:
            return
        values = settings_of(settings.data)
        tls = "tls_cert" in values
        # The daemon's own checks (settings.py), as far as the fake models them: a TLS pair it can trust.
        tls_ok = all(
            path in self.files and self.files[path].owner == USER and not self.files[path].is_symlink
            for path in (plan.TLS_KEY_PATH, plan.TLS_CERT_PATH)
        )
        if self.inject.refuse_start or (tls and not tls_ok):
            self._append(plan.STARTUP_REFUSED_PATH, b"jwicket: refused to start: settings check failed\n")
            self.daemon = None
            return
        bundle = bundle_identity(file.data)
        port = int(values.get("port", "8443"))
        bind = values.get("bind", plan.LOOPBACK)
        backend = values.get("backend", "netconf")
        routing_instance = values.get("routing_instance")
        for _ in range(2 if self.inject.restart_loop else 1):
            self.next_pid += 1
            stamp = self.device_time().strftime("%Y-%m-%d %H:%M:%S")
            # app.py's start line: 'listening on %s:%d tls=%s backend=%s routing_instance=%s version=%s payload=%s'
            line = (
                f"{stamp},000 INFO jwicket listening on {bind}:{port} tls={tls} backend={backend} "
                f"routing_instance={routing_instance or 'default'} version={bundle.version} "
                f"payload={bundle.payload_short}"
            )
            self._append(plan.LOG_PATH, (line + "\n").encode("ascii"))
            record = {"event": "start", "version": bundle.version, "payload_sha256": bundle.payload_sha256}
            self._append(plan.AUDIT_PATH, (json.dumps(record, sort_keys=True) + "\n").encode("ascii"))
        self.daemon = Daemon(
            self.next_pid, bundle.version, bundle.payload_sha256, port, identity, bind, tls, routing_instance
        )
        self.calls.append(("daemon-start", self.next_pid))

    def _append(self, path: str, data: bytes) -> None:
        if plan.STATE_DIR not in self.files:
            return
        existing = self.files.get(path)
        if existing is None:
            self.files[path] = FakeFile(data, owner=USER, mode=0o600)
        else:
            existing.data += data

    def https(self, address: str, port: int, path: str, host: str, pin: str) -> transport.HttpsResult:
        """C8 from the op script: transport.https_get's contract (nothing sent before the pin matches)."""
        self.record(("https", address, port, path, host, pin))
        daemon = self.daemon
        listening = daemon is not None and daemon.tls and (daemon.bind, daemon.port) == (address, port)
        if self.inject.https_refused or daemon is None or not listening:
            return transport.HttpsResult(False, reason=f"TCP to {address}:{port} failed: connection refused (fake)")
        cert = self.files.get(plan.TLS_CERT_PATH)
        presented = transport.pem_certificate_sha256(cert.data) if cert is not None else None
        if presented != pin:
            return transport.HttpsResult(True, False, reason="another certificate (fake)", peer_sha256=presented)
        if host != plan.host_port(address, port):
            return transport.HttpsResult(True, True, b"HTTP/1.1 421 Misdirected Request\r\n\r\n{}")
        body = json.dumps({"version": daemon.version, "build": daemon.payload[:16]})
        return transport.HttpsResult(True, True, f"HTTP/1.1 200 OK\r\n\r\n{body}".encode("ascii"), peer_sha256=pin)

    # -- replies ---------------------------------------------------------------------------------------

    def software_information(self) -> str:
        host = f"<host-name>{self.hostname}</host-name>" if self.hostname else ""
        return (
            "<rpc-reply><software-information>"
            f"{host}<product-model>{self.model}</product-model><product-name>{self.model}</product-name>"
            f"<junos-version>{self.release}</junos-version></software-information></rpc-reply>"
        )

    def commit_information(self) -> str:
        parts = ["<rpc-reply><commit-information>"]
        for index, entry in enumerate(self.history[:50]):
            parts.append(f"<commit-history><sequence-number>{index}</sequence-number>")
            parts.append(f"<date-time>{entry.time.strftime('%Y-%m-%d %H:%M:%S')} UTC</date-time>")
            parts.append(f"<user>{escape(entry.user)}</user><client>{escape(entry.client)}</client>")
            if entry.comment:
                parts.append(f"<comment>{escape(entry.comment)}</comment>")
            if entry.confirmed:
                parts.append(f"<commit-confirmed>{escape(entry.confirmed)}</commit-confirmed>")
            parts.append("</commit-history>")
        parts.append("</commit-information></rpc-reply>")
        return "".join(parts)

    def file_list(self, path: str) -> str:
        info = self.files.get(path)
        if info is None or not info.is_dir:
            return (
                "<rpc-reply><directory-list>"
                f"<output>{escape(path)}: No such file or directory</output></directory-list></rpc-reply>"
            )
        parts = [f"<rpc-reply><directory-list><directory><directory-name>{escape(path)}</directory-name>"]
        for name, entry in sorted(self.files.items()):
            parent, _, base = name.rpartition("/")
            if parent != path:
                continue
            kind = "d" if entry.is_dir else ("l" if entry.is_symlink else "-")
            perms = "".join(ch if entry.mode & (1 << (8 - i)) else "-" for i, ch in enumerate("rwxrwxrwx"))
            parts.append(
                "<file-information>"
                f"<file-name>{escape(base)}</file-name>"
                + ("<file-directory/>" if entry.is_dir else "")
                + f'<file-permissions format="{kind}{perms}">{entry.mode:o}</file-permissions>'
                f"<file-owner>{escape(entry.owner)}</file-owner><file-group>wheel</file-group>"
                f"<file-size>{len(entry.data) if not entry.is_dir else 512}</file-size>"
                "</file-information>"
            )
        parts.append("</directory></directory-list></rpc-reply>")
        return "".join(parts)

    def status_output(self) -> str:
        if self.daemon is None:
            return "<rpc-reply><output>warning: No active extension-services</output></rpc-reply>"
        return (
            "<rpc-reply><output>Extension service application details:\n"
            f"Name : jwicket.py\nProcess-id: {self.daemon.pid}\n</output></rpc-reply>"
        )

    def start_app(self, app: str) -> str:
        path = f"{plan.JET_DIR}/{app}"
        stanza = " ".join((*plan.STANZA_KEYS["F-SELFTEST"][:-1], app))
        if not self.effective().under(stanza) or path not in self.files:
            raise FakeErrors.RpcError(f"error: application {app} is not configured")
        bundle = bundle_identity(self.files[path].data)
        if app == plan.SELFTEST_FILE:
            body: Dict[str, Any] = {
                "version": bundle.version,
                "payload_sha256": bundle.payload_sha256,
                "ok": True,
                "failures": [],
            }
            result = plan.SELFTEST_RESULT_PATH
        else:
            modules = ("http.server", "ssl", "json", "hmac", "threading", "jnpr.junos", "lxml", "ncclient", "paramiko")
            body = {"jwicket": bundle.version, "modules": {m: "ok" for m in modules}}
            result = plan.PROBE_RESULT_PATH
        directory = self.files.get(plan.STATE_DIR)
        if directory is not None and directory.owner == USER and not directory.mode & 0o022:
            self.files[result] = FakeFile(json.dumps(body, sort_keys=True).encode("ascii"), owner=USER, mode=0o600)
        return "<rpc-reply><ok/></rpc-reply>"

    # -- RPC dispatch ----------------------------------------------------------------------------------

    def rpc(self, name: str, args: Mapping[str, Any], session: int) -> str:
        self.record(("rpc", name, dict(args), session))
        if session in self.dead_sessions:
            raise FakeErrors.ConnectClosedError("the session closed (fake)")
        if name == "get-software-information":
            return self.software_information()
        if name == "get-chassis-cluster-status":
            return "<rpc-reply><error><message>Chassis cluster is not enabled.</message></error></rpc-reply>"
        if name == "get-chassis-inventory":
            return (
                "<rpc-reply><chassis-inventory><chassis><name>Chassis</name><serial-number>FIXTURE-SN-0001"
                "</serial-number><chassis-module><name>Routing Engine 0</name></chassis-module></chassis>"
                "</chassis-inventory></rpc-reply>"
            )
        if name == "get-flow-session-information":
            return (
                "<rpc-reply><flow-session-information><flow-session-summary-information>"
                "<active-sessions>12</active-sessions></flow-session-summary-information>"
                "</flow-session-information></rpc-reply>"
            )
        if name == "get-commit-information":
            return self.commit_information()
        if name == "get-rollback-information":
            delta = fakes_junos.rollback_delta(self.history, int(str(args["rollback"])), int(str(args["compare"])))
            return (
                "<rpc-reply><rollback-information>"
                f"<configuration-output>{escape(delta)}</configuration-output></rollback-information></rpc-reply>"
            )
        if name == "file-list":
            return self.file_list(str(args["path"]))
        if name == "get-sha256-checksum-information":
            info = self.files.get(str(args["path"]))
            if info is None or info.is_dir:
                raise FakeErrors.RpcError(f"{args['path']}: No such file or directory")
            return (
                "<rpc-reply><checksum-information><file-checksum><computation-method>SHA256</computation-method>"
                f"<input-file>{escape(str(args['path']))}</input-file><checksum>{info.sha256}</checksum>"
                "</file-checksum></checksum-information></rpc-reply>"
            )
        if name == "file-show":
            info = self.files.get(str(args["filename"]))
            if info is None or info.is_dir:
                raise FakeErrors.RpcError(f"{args['filename']}: No such file or directory")
            return f"<rpc-reply><file-content>{escape(info.data.decode('utf-8', 'replace'))}</file-content></rpc-reply>"
        if name == "jet-application-status":
            return self.status_output()
        return self._write(name, args)

    def _write(self, name: str, args: Mapping[str, Any]) -> str:
        if name == "file-change-permission":
            path = str(args["filename"])
            if path not in self.files:
                raise FakeErrors.RpcError(f"{path}: No such file or directory")
            self.files[path].mode = int(str(args["permission"]), 8)
            return "<ok/>"
        if name == "file-delete":
            path = str(args["path"])
            if path not in self.files or self.files[path].is_dir:
                raise FakeErrors.RpcError(f"error: {path}: No such file or directory")
            del self.files[path]
            return "<ok/>"
        if name == "file-copy":
            source, destination = str(args["source"]), str(args["destination"])
            if source.startswith(("http://", "https://")):
                data = self.inject.pull_files.get(source)
                if data is None:
                    raise FakeErrors.RpcError(f"error: fetch of {source} failed")
                mode = 0o644
            else:
                if source not in self.files:
                    raise FakeErrors.RpcError(f"error: {source}: No such file or directory")
                data, mode = self.files[source].data, self.files[source].mode
            if destination in self.files and self.inject.refuse_overwrite:
                raise FakeErrors.RpcError(f"error: {destination}: File exists")
            self.files[destination] = FakeFile(data, owner=self.inject.copy_owner or USER, mode=mode)
            return "<ok/>"
        if name == "extension-service-start":
            return self.start_app(str(args["application-name"]))
        if name == "extension-service-stop":
            if self.daemon is not None and not self.inject.stop_ignored:
                self.daemon = None
            return "<ok/>"
        raise AssertionError(f"unhandled RPC {name}")

    # -- what the tests look at ------------------------------------------------------------------------

    def names(self) -> List[str]:
        return [str(c[1]) if c[0] == "rpc" else str(c[0]) for c in self.calls]

    def writes(self) -> List[Tuple[Any, ...]]:
        return [c for c in self.calls if c[0] in WRITE_CALLS or (c[0] == "rpc" and c[1] in transport.WRITE_RPCS)]

    def commits_by(self, user: str) -> List[Entry]:
        return [e for e in self.history if e.user == user and e.client == "netconf"]


