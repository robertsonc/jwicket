class FakeRpc:
    def __init__(self, device: FakeDevice) -> None:
        self._device = device

    def __getattr__(self, attr: str) -> Callable[..., str]:
        name = attr.replace("_", "-")

        def call(*vargs: Any, **kwargs: Any) -> str:
            assert not vargs, f"{name}: positional arguments are only for get_configuration"
            assert kwargs.pop("dev_timeout") == plan.TIMEOUTS["rpc"], f"{name}: no RPC timeout"
            args = {k.replace("_", "-"): v for k, v in kwargs.items()}
            return self._device.box.rpc(name, args, self._device.session)

        return call

    def get_config(self, filter_xml: Any = None, options: Optional[Mapping[str, str]] = None, **kwargs: Any) -> str:
        device = self._device
        assert kwargs.get("dev_timeout") == plan.TIMEOUTS["rpc"]
        assert filter_xml == transport.CONFIG_FILTER, "the select-only filter of spec 8.3"
        options = dict(options or {})
        device.box.record(("get-configuration", options.get("database"), options.get("inherit"), device.session))
        if device.session in device.box.dead_sessions:
            raise FakeErrors.ConnectClosedError("the session closed (fake)")
        box = device.box
        model = box.candidate if options.get("database") == "candidate" else box.committed
        return config_xml(
            fakes_junos.selected(plan.expand_groups(model) if options.get("inherit") == "inherit" else model)
        )

    def get_configuration(self, attrs: Mapping[str, str], **kwargs: Any) -> str:
        device = self._device
        box = device.box
        assert attrs.get("compare") == "rollback" and attrs.get("format") == "text"
        box.record(("compare", attrs.get("rollback"), device.session))
        if device.session in box.dead_sessions:
            raise FakeErrors.ConnectClosedError("the session closed (fake)")
        if box.inject.compare_unreadable:  # SC-01: a reply without <configuration-output> (Q-INST-01's shape)
            return "<rpc-reply><configuration-information/></rpc-reply>"
        extra = ""
        if attrs.get("rollback") == "1":
            if box.inject.next_delta_unreadable:
                box.inject.next_delta_unreadable = False
                return "<rpc-reply><configuration-information/></rpc-reply>"
            extra, box.inject.next_delta_extra = box.inject.next_delta_extra, ""
        if attrs.get("rollback") == "0":
            text = plan.patch_text(box.committed, box.candidate)
        else:
            text = box.history[0].delta if box.candidate == box.committed and box.history else ""
        return f"<rpc-reply><configuration-output>{escape(text + extra)}</configuration-output></rpc-reply>"


class FakeDevice:
    """jnpr.junos.Device in local mode: constructed with no arguments (no host, no credentials)."""

    def __init__(self, box: FakeBox) -> None:
        self.box = box
        self.session = 0
        self.timeout: Optional[int] = None
        self.rpc = FakeRpc(self)

    def open(self) -> None:
        box = self.box
        box.sessions += 1
        self.session = box.sessions
        box.calls.append(("open", self.session))

    def close(self) -> None:
        box = self.box
        box.calls.append(("close", self.session))
        if box.lock_owner == self.session:
            box.lock_owner = None
            box.candidate = box.committed


class FakeConfig:
    """jnpr.junos.utils.config.Config with mode='exclusive': lock on enter, unlock on exit."""

    def __init__(self, dev: FakeDevice, mode: Optional[str] = None) -> None:
        assert mode == "exclusive", "the op script locks with Config(dev, mode='exclusive')"
        self.dev = dev
        self.box = dev.box

    def _alive(self, call: Tuple[Any, ...]) -> None:
        self.box.record(call)
        if self.dev.session in self.box.dead_sessions:
            raise FakeErrors.ConnectClosedError("the session closed (fake)")

    def __enter__(self) -> FakeConfig:
        self._alive(("lock", self.dev.session))
        box = self.box
        if box.inject.lock_refused or (box.lock_owner is not None and box.lock_owner != self.dev.session):
            raise FakeErrors.LockError("configuration database locked by otheradmin")
        if box.candidate != box.committed:
            raise FakeErrors.LockError("configuration database modified")
        box.lock_owner = self.dev.session
        return self

    def __exit__(self, *exc: Any) -> None:
        self._alive(("unlock", self.dev.session))
        if self.box.lock_owner == self.dev.session:
            self.box.lock_owner = None
            self.box.candidate = self.box.committed

    def load(self, text: str, format: str) -> None:  # noqa: A002 - PyEZ's keyword
        assert format == "set"
        lines = text.split("\n")
        self._alive(("load", tuple(lines), self.dev.session))
        if self.box.lock_owner != self.dev.session:
            raise FakeErrors.ConfigLoadError("not locked")
        for line in lines:
            if not line.startswith(("set ", "delete ")):
                raise FakeErrors.ConfigLoadError(f"syntax error: {line}")
        self.box.candidate = plan.apply_lines(self.box.candidate, lines)

    def rollback(self, rb_id: int = 0) -> None:
        self._alive(("rollback", rb_id, self.dev.session))
        box = self.box
        if rb_id == 0:
            box.candidate = box.committed
        else:
            box.candidate = box.pending.previous if box.pending is not None else box.committed

    def commit(
        self, comment: Optional[str] = None, confirm: Optional[int] = None, timeout: Optional[int] = None
    ) -> bool:
        assert timeout == plan.TIMEOUTS["commit"], "a commit carries its 120 s timeout"
        self._alive(("commit", comment, confirm, self.dev.session))
        box = self.box
        if box.lock_owner != self.dev.session:
            raise FakeErrors.CommitError("not locked")
        box.commit_model(
            box.candidate, user=USER, client="netconf", comment=comment, confirm=confirm, session=self.dev.session
        )
        return True


