def config_xml(model: StatementSet) -> str:
    """The model as the XML state.statements_from_config reads (keyed lists under file, client, groups)."""
    root = ET.Element("configuration")

    def child(node: ET.Element, tag: str, name: Optional[str] = None) -> ET.Element:
        for existing in node:
            if existing.tag != tag:
                continue
            found = existing.find("name")
            if (name is None and found is None) or (name is not None and found is not None and found.text == name):
                return existing
        made = ET.SubElement(node, tag)
        if name is not None:
            ET.SubElement(made, "name").text = name
        return made

    for key, value in sorted(model.pairs):
        tokens = key.split(" ")
        if tokens == ["apply-groups"]:
            ET.SubElement(root, "apply-groups").text = value
            continue
        node = root
        index = 0
        while index < len(tokens):
            token = tokens[index]
            last = index == len(tokens) - 1
            if token in LIST_PARENTS and not last:
                node = child(node, token, tokens[index + 1])
                index += 2
                continue
            if last:
                leaf = child(node, token)
                if value:
                    leaf.text = value
            else:
                node = child(node, token)
            index += 1
    inner = "".join(ET.tostring(c, encoding="unicode") for c in root)
    return f"<rpc-reply><configuration>{inner}</configuration></rpc-reply>"


