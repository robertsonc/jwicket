"""Fakes of on-box PyEZ, ``jcs`` and a lab vSRX for the op-script installer tests (Spec 006 AC-006-32).

Nothing here talks to a device, and nothing here proves what a device does: the fakes encode the
installer's reading of Junos (every reply shape is synthetic, shaped like tests/fixtures/install/; lab
test Q-INST-01 records the real ones). They give a model that keeps state across a run (configuration,
commit history with deltas, a pending confirmed commit with its deadline, files with owners and modes, a
daemon that starts when its stanza, file and settings allow it and listens where its settings say), record
every call in order, and can inject the failures the tests need (a refused start, a foreign pending
commit, a stop that is ignored, a missing download, an HTTPS connection the box refuses).

The base box follows the lab facts (docs/evidence/2026-11-24-srx4100-lab): /var/db/jwicket exists, made by
root and given to the account (R4: the installer never creates it), and holds the operator's TLS pair made
in the shell (``plan.shell_tls_lines``; R2 on the box: the op script never makes it). ``lab_srx4100_box``
is R5's reference case. The certificate and key are placeholders, not a real certificate or key.

``FakeDevice`` and ``FakeConfig`` stand in for ``jnpr.junos.Device`` (local mode, no host) and
``jnpr.junos.utils.config.Config``; ``FakeErrors`` for ``jnpr.junos.exception``; ``FakeJcs`` for Junos's
``jcs`` module; ``FakeLocalFiles`` for the script's own file access. Every RPC passes
``transport.check_rpc`` in the executor, so a name or argument outside ``INSTALL_RPCS`` fails the test.
"""

