class FakeJcs:
    """Junos's jcs module: get_input pops the next answer ("" when none is left) and records the prompt
    with how much output had been printed when it was asked. The access and listen-address prompts are
    answered from their own values (``access``, ``listen``), and, when ``overrides`` is given, each
    override prompt with its flag if the flag is in it (else Enter), so most tests list only the gate's
    answers."""

    def __init__(
        self,
        answers: Sequence[str],
        out: io.StringIO,
        box: FakeBox,
        *,
        access: str = "",
        listen: str = LISTEN,
        overrides: Optional[Sequence[str]] = None,
    ) -> None:
        self.answers = list(answers)
        self.out = out
        self.box = box
        self.access = access
        self.listen = listen
        self.overrides = None if overrides is None else set(overrides)
        self.prompts: List[Tuple[str, int, int]] = []

    def get_input(self, prompt: str) -> str:
        self.prompts.append((prompt, len(self.out.getvalue()), len(self.box.calls)))
        self.box.record(("prompt", prompt[:40]))  # a hook may act while the operator reads the prompt
        if prompt.startswith(op_template.ACCESS_PROMPT_HEAD):
            return self.access
        if prompt.startswith(op_template.LISTEN_PROMPT_HEAD):
            return self.listen
        if self.overrides is not None and " can be overridden: type " in prompt:
            flag = prompt.split(" can be overridden: type ", 1)[1].split(" ", 1)[0]
            return flag if flag in self.overrides else ""
        return self.answers.pop(0) if self.answers else ""

    def asked(self) -> List[str]:
        """The prompts other than the access and listen-address ones, in order."""
        heads = (op_template.ACCESS_PROMPT_HEAD, op_template.LISTEN_PROMPT_HEAD)
        return [p for p, _, _ in self.prompts if not p.startswith(heads)]


class FakeLocalFiles(op_template.LocalFiles):
    """The script's own file access, on the fake device's files: the same checks as LocalFiles, by owner
    name (UID is USER) instead of uid."""

    def __init__(self, box: FakeBox) -> None:
        super().__init__("")
        self.box = box
        self.writes: List[str] = []

    def _owner_ok(self, info: FakeFile, uid: int) -> bool:
        return uid == UID and info.owner == USER

    def exists(self, path: str) -> bool:
        return path in self.box.files

    def read_once(self, path: str, uid: int, limit: int) -> bytes:
        info = self.box.files.get(path)
        if info is None:
            raise op_template.LocalFileError(f"{path} could not be opened: No such file or directory")
        if info.is_symlink:
            raise op_template.LocalFileError(f"{path} could not be opened without following a link")
        if info.is_dir:
            raise op_template.LocalFileError(f"{path} is not a regular file")
        if not self._owner_ok(info, uid):
            raise op_template.LocalFileError(f"{path} is not owned by the account running this script")
        if info.mode & 0o022:
            raise op_template.LocalFileError(f"{path} is writable by group or others")
        if len(info.data) > limit:
            raise op_template.LocalFileError(f"{path} is too large")
        return info.data

    def write_new(self, path: str, data: bytes, mode: int) -> None:
        self.box.record(("local-write", path, mode))
        if path in self.box.files:
            raise op_template.LocalFileError(f"{path} could not be created: File exists")
        if path.rpartition("/")[0] not in self.box.files:
            raise op_template.LocalFileError(f"{path} could not be created: No such file or directory")
        self.box.files[path] = FakeFile(data, owner=USER, mode=mode)
        self.writes.append(path)

    def state_dir_trusted(self, uid: int) -> bool:
        info = self.box.files.get(plan.STATE_DIR)
        return info is not None and info.is_dir and self._owner_ok(info, uid) and not info.mode & 0o022

    def write_private(self, path: str, data: bytes, mode: int, uid: int) -> None:
        self.box.record(("local-write", path, mode))
        if path.rpartition("/")[0] != plan.STATE_DIR:
            raise op_template.LocalFileError(f"{path} is not a file in {plan.STATE_DIR}")
        if not self.state_dir_trusted(uid):
            raise op_template.LocalFileError(f"{plan.STATE_DIR} is not trusted")
        existing = self.box.files.get(path)
        if existing is not None and (existing.is_symlink or existing.is_dir or existing.owner != USER):
            raise op_template.LocalFileError(f"{path} exists and is not a regular file owned by this account")
        self.box.files[path] = FakeFile(data, owner=USER, mode=mode)
        self.writes.append(path)


@dataclass
class Harness:
    """One op-script run against ``box``: the bundle at its per-tag URL (or in the home directory), the
    typed answers in order, and the veriexec read."""

    box: FakeBox = field(default_factory=FakeBox)
    bundle: bytes = field(default_factory=make_bundle)
    answers: List[str] = field(default_factory=list)
    sysctl: Tuple[Optional[str], str] = (ENFORCING, "")
    home_copy: bool = False
    access: str = ""  # Enter at the access prompt: tls, the default
    listen: str = LISTEN
    overrides: Optional[Tuple[str, ...]] = None
    out: io.StringIO = field(default_factory=io.StringIO)
    jcs: Optional[FakeJcs] = None
    files: Optional[FakeLocalFiles] = None

    def __post_init__(self) -> None:
        self.box.inject.pull_files[URL] = self.bundle
        if self.home_copy:
            self.box.files[f"{HOME}/jwicket.py"] = FakeFile(self.bundle, owner=USER, mode=0o644)

    def run(self, *answers: str, **main_kwargs: Any) -> int:
        self.out = io.StringIO()
        self.jcs = FakeJcs(
            [*self.answers, *answers],
            self.out,
            self.box,
            access=self.access,
            listen=self.listen,
            overrides=self.overrides,
        )
        self.files = FakeLocalFiles(self.box)
        kwargs: Dict[str, Any] = {
            "jcs_module": self.jcs,
            "pyez": (lambda: FakeDevice(self.box), FakeConfig, FakeErrors),
            "account": op_template.Account(UID, USER, HOME),
            "clock": self.box.clock,
            "out": self.out,
            "files": self.files,
            "sysctl": lambda: self.sysctl,
            "https": self.box.https,
            "xml": lambda text: text,
            "now": lambda: "2026-11-24T21:30:00Z",
        }
        kwargs.update(main_kwargs)
        return op_template.main(payload_text(self.bundle), **kwargs)

    @property
    def output(self) -> str:
        return self.out.getvalue()

    def output_before_prompt(self, index: int = 0) -> str:
        assert self.jcs is not None
        return self.output[: self.jcs.prompts[index][1]]

    def gate_index(self) -> int:
        """The position in box.calls of the lab-gate prompt."""
        assert self.jcs is not None
        for prompt, _, call_index in self.jcs.prompts:
            if prompt == plan.LAB_GATE_PROMPT:
                return call_index
        raise AssertionError("the lab gate was never asked")

    def receipt(self) -> plan.Receipt:
        return plan.Receipt.from_json(self.box.files[plan.RECEIPT_PATH].data.decode("utf-8"))


def install_answers(host: str = HOST) -> List[str]:
    """Answers for a plain install: the host name at the gate (access and address come from the harness)."""
    return [host]


def installed_box(box: Optional[FakeBox] = None, **harness: Any) -> Tuple[FakeBox, Harness]:
    """A box after a successful M4 install (bootstrap pasted, op script run, access and host name typed)."""
    box = box or FakeBox()
    box.paste_bootstrap()
    run = Harness(box, **harness)
    code = run.run(HOST)
    assert code == plan.EXIT_OK, run.output
    return box, run


def plan_options(access: str = "tls") -> plan.Options:
    """The options the op script uses for a release-URL install: the netconf backend, and --access tls on
    LISTEN, port 9443 (or --access tunnel, 127.0.0.1:8443)."""
    listen = LISTEN if access == "tls" else None
    return plan.Options(user=USER, transfer="file-copy", pull_url=URL, access=access, listen_address=listen)


def lab_srx4100_box(*, manual_install: bool = True) -> FakeBox:
    """Revision R5's reference case (docs/evidence/2026-11-24-srx4100-lab): a physical SRX4100 on
    25.2R1-S1.4, standalone, managed by Security Director Cloud over outbound-ssh, with 'system
    management-instance' (fxp0 in mgmt_junos) and NETCONF on. With ``manual_install``, what the lab run
    left: language python3, the three stanzas without checksums, an older bundle's files, deploy-lab's
    settings, the on-box TLS pair, and the daemon running. Values other than the model, the release and the
    lab's settings are placeholders."""
    app = " ".join(plan.STANZA_KEYS["F-DAEMON"][:-1])
    config: List[Tuple[str, str]] = [
        (plan.MANAGEMENT_INSTANCE_KEY, ""),
        ("system services outbound-ssh client sd-cloud", ""),
        ("system services netconf ssh", ""),
    ]
    if manual_install:
        config += [
            ("system scripts language", "python3"),
            (f"{app} {plan.DAEMON_FILE} daemonize", ""),
            (f"{app} {plan.DAEMON_FILE} respawn-on-normal-exit", ""),
            (f"{app} {plan.DAEMON_FILE} username", USER),
            (f"{app} {plan.SELFTEST_FILE} username", USER),
            (f"{app} {plan.PROBE_FILE} username", USER),
        ]
    box = FakeBox(config=config, hostname=SRX4100_HOST, model="srx4100", release=SRX4100_RELEASE)
    if manual_install:
        old = make_bundle(payload="32" * 32, filler="the lab run's bundle")
        for name in plan.JWICKET_JET_FILES:
            box.files[f"{plan.JET_DIR}/{name}"] = FakeFile(old, owner=USER, mode=0o644)
        settings = (
            "[server]\n"
            f"bind = {LISTEN}\nport = {plan.DEFAULT_TLS_PORT}\nrouting_instance = {plan.MGMT_INSTANCE}\n"
            f"tls_cert = {plan.TLS_CERT_PATH}\ntls_key = {plan.TLS_KEY_PATH}\n"
            f"allowed_hosts = {LISTEN}:{plan.DEFAULT_TLS_PORT}\n\n"
            f"[log]\nfile = {plan.LOG_PATH}\naudit_file = {plan.AUDIT_PATH}\n"
        )
        box.files[plan.SETTINGS_PATH] = FakeFile(settings.encode("ascii"), owner=USER, mode=0o600)
        box.reconcile()
    return box


